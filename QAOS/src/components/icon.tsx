/** Used by the Generator module's category/nav components. */
export function CategoryIcon({ name, className }: { name: string; className?: string }) {
  const Cmp = ICONS[name] ?? FlaskConical;
  return <Cmp className={className} />;
}

/** Used by the Notes module's category/nav components. */
export function DynamicIcon({ name, className, style }: { name: string; className?: string; style?: CSSProperties }) {
  const Cmp = ICONS[name] ?? FileText;
  return <Cmp className={className} style={style} />;
}
